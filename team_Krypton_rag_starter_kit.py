def smart_answer(question, top_k=5):
    """
    Generate an answer grounded in retrieved document passages.
    Returns the answer and source evidence.
    """

    if not question or not question.strip():
        return "Please enter a question.", []

    passages = smart_retrieve(question, top_k=top_k)

    if not passages:
        return (
            "The answer could not be found in the provided document.",
            []
        )

    # Build context with source information.
    context_parts = []

    for i, passage in enumerate(passages, start=1):
        source = passage.get("source") or "Source filename unavailable"
        page = passage.get("page")
        page_text = f"Page {page}" if page is not None else "Page unavailable"

        context_parts.append(
            f"[Passage {i}]\n"
            f"Source: {source}\n"
            f"{page_text}\n"
            f"Similarity: {passage['similarity']:.3f}\n"
            f"Text:\n{passage['text']}"
        )

    context = "\n\n".join(context_parts)

    prompt = f"""
Answer the student's question using only the evidence below.

QUESTION:
{question}

DOCUMENT EVIDENCE:
{context}

REQUIREMENTS:
- Do not invent policies or facts.
- Cite source filenames and page numbers when available.
- If the evidence does not answer the question, say so clearly.
- If the evidence is incomplete, explain what is missing.
- Do not present similarity scores as proof of factual correctness.

Write a clear, concise answer.
"""

    try:
        reply = generate(
            prompt,
            system_text=ANSWER_RULES,
            temperature=0.1
        )

        return reply, passages

    except Exception as exc:
        print("Answer generation error:", exc)

        return (
            "I couldn't generate an answer right now. "
            "Please try again.",
            passages
        )


